// Generates supabase/migrations/0062_lock_at_kickoff.sql from
// src/data/games.ts.
//
// The kickoff times live in a TypeScript file the database cannot read,
// so locking a pick at kickoff in RLS means the database needs its own
// copy of them. That copy has exactly one job: never disagree with
// src/data/games.ts. Hand-maintaining 273 timestamps in a second place is
// how it would come to disagree, so it is generated, and
// scripts/lock-at-kickoff.test.mjs fails if the committed file is not
// what this script produces from the current schedule.
//
//   node scripts/gen-kickoff-migration.mjs          # write the file
//   node scripts/gen-kickoff-migration.mjs --check  # exit 1 if stale
//
// The output is idempotent from top to bottom - create if not exists,
// upsert every row, drop and recreate every policy - so when the schedule
// changes you regenerate it and paste the same file again.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "supabase", "migrations", "0062_lock_at_kickoff.sql");

// Same shape sync-results.mjs uses: a plain regex over the source, rather
// than importing a module with path aliases into a bare node script.
export function parseGames(source) {
  const re = /\{\s*id:\s*"([^"]+)",\s*week:\s*(\d+),\s*away:\s*"([A-Z]{2,3})",\s*home:\s*"([A-Z]{2,3})",\s*kickoff:\s*"([^"]+)"/g;
  const games = [];
  let m;
  while ((m = re.exec(source)) !== null) {
    games.push({ id: m[1], week: Number(m[2]), kickoff: m[5] });
  }
  return games;
}

// A single-quoted SQL literal. Every value here comes from our own
// checked-in source file, but generating SQL by concatenation without
// escaping is a habit worth not having.
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

export function buildSql(games) {
  const rows = games
    .map((g) => `  (${lit(g.id)}, ${g.week}, ${lit(g.kickoff)}::timestamptz)`)
    .join(",\n");

  return `-- Picks lock when the game kicks off.
--
-- GENERATED by scripts/gen-kickoff-migration.mjs from src/data/games.ts.
-- Do not edit by hand - regenerate and re-run. Idempotent end to end, so
-- running it again after a schedule change is the update.
--
-- What this replaces: until now the only thing that closed picking was
-- weeks.is_open, a boolean somebody flips in the admin panel. That is a
-- chore, not a deadline, and the first Wednesday night of the season is
-- what it cost - the game kicked off at 8:20 ET, the flag never got
-- flipped, and every account could still change its pick on a game that
-- had already been played.
--
-- Per game, not per week. Closing the whole slate at the week's first
-- kickoff would freeze Sunday's fifteen games on Wednesday night.
-- weeks.is_open stays on top of this as a manual override; it is just no
-- longer the only thing standing between a played game and an edit.

-- The database's own copy of the kickoff times. Readable by anyone (they
-- are printed on the board already), writable by admins only - a user who
-- could edit this table could move a kickoff into the future and reopen a
-- game they had just watched.
create table if not exists public.game_kickoffs (
  game_id text primary key,
  week integer not null,
  kickoff timestamptz not null
);
create index if not exists game_kickoffs_week_idx on public.game_kickoffs (week);
alter table public.game_kickoffs enable row level security;

drop policy if exists "game_kickoffs_select_all" on public.game_kickoffs;
create policy "game_kickoffs_select_all" on public.game_kickoffs for select using (true);
drop policy if exists "game_kickoffs_insert_admin" on public.game_kickoffs;
create policy "game_kickoffs_insert_admin" on public.game_kickoffs for insert with check (public.is_admin());
drop policy if exists "game_kickoffs_update_admin" on public.game_kickoffs;
create policy "game_kickoffs_update_admin" on public.game_kickoffs for update using (public.is_admin());
drop policy if exists "game_kickoffs_delete_admin" on public.game_kickoffs;
create policy "game_kickoffs_delete_admin" on public.game_kickoffs for delete using (public.is_admin());

-- The schedule, ${games.length} games, straight from src/data/games.ts.
insert into public.game_kickoffs (game_id, week, kickoff) values
${rows}
on conflict (game_id) do update
  set week = excluded.week,
      kickoff = excluded.kickoff;

-- The rule itself.
--
-- Written as "there IS a row and it is in the future", not "there is NO
-- row saying it started". The difference is what happens to a game_id the
-- table has never heard of: this way it cannot be picked at all, which is
-- loud, obvious and one paste away from fixed. The other way it would be
-- freely editable forever, which is silent, and is the exact bug this
-- migration exists to close. Fail shut.
create or replace function public.game_is_open(p_game_id text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.game_kickoffs k
    where k.game_id = p_game_id and k.kickoff > now()
  );
$$;

drop policy if exists "weekly_picks_insert_own" on public.weekly_picks;
create policy "weekly_picks_insert_own" on public.weekly_picks for insert
  with check (
    auth.uid() = user_id
    and exists (select 1 from public.weeks w where w.week = weekly_picks.week and w.is_open = true)
    and public.game_is_open(weekly_picks.game_id)
  );

drop policy if exists "weekly_picks_update_own" on public.weekly_picks;
create policy "weekly_picks_update_own" on public.weekly_picks for update
  using (
    auth.uid() = user_id
    and exists (select 1 from public.weeks w where w.week = weekly_picks.week and w.is_open = true)
    and public.game_is_open(weekly_picks.game_id)
  );

drop policy if exists "weekly_picks_delete_own" on public.weekly_picks;
create policy "weekly_picks_delete_own" on public.weekly_picks for delete
  using (
    auth.uid() = user_id
    and exists (select 1 from public.weeks w where w.week = weekly_picks.week and w.is_open = true)
    and public.game_is_open(weekly_picks.game_id)
  );
`;
}

export function generate() {
  const source = readFileSync(join(ROOT, "src", "data", "games.ts"), "utf8");
  const games = parseGames(source);
  // The same guard sync-results.mjs uses. A regex that quietly stops
  // matching (someone reformats games.ts, adds a field before kickoff)
  // would otherwise generate a migration that unlocks the season.
  if (games.length < 200) {
    throw new Error(
      `Only parsed ${games.length} games out of src/data/games.ts - a full season is 272. ` +
        `The parser in this script has probably drifted from the file's formatting.`,
    );
  }
  return buildSql(games);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = generate();
  if (process.argv.includes("--check")) {
    const onDisk = readFileSync(OUT, "utf8");
    if (onDisk !== sql) {
      console.error("0062_lock_at_kickoff.sql is stale - run: node scripts/gen-kickoff-migration.mjs");
      process.exit(1);
    }
    console.log("0062_lock_at_kickoff.sql matches src/data/games.ts");
  } else {
    writeFileSync(OUT, sql);
    console.log(`Wrote ${OUT}`);
  }
}

export { OUT };
